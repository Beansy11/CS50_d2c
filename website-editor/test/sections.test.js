const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const L = require('../../out/website-editor/src/links.js');
const P = require('../../out/website-editor/src/pageEdit.js');
const E = require('../../out/website-editor/src/pageEditor.js');
const S = require('../../out/website-editor/src/siteFiles.js');

// An imported page: its own sections, an id, a script and a drawing.
const IMPORTED = `<!DOCTYPE html>
<html>
<head>
    <title>Shop</title>
</head>
<body>
    <header id="top-bar"><h1>Shop</h1></header>
    <section class="prices">
        <h2>Our Prices!</h2>
        <p>Cheap.</p>
        <svg id="logo"><rect id="logo-shape"/></svg>
    </section>
    <h2>Café</h2>
    <p id="has space">x</p>
    <script>let a = 1;</script>
</body>
</html>
`;

// A page made in Draw2Code: everything placed in its wrapper, each with an id.
const GENERATED = `<!DOCTYPE html>
<html lang="en">
<head>
  <title>Home</title>
  <!-- Generated by Draw2Code Web Editor -->
</head>
<body>
  <div class="page">
    <svg id="rect-1" width="100" height="50" viewBox="0 0 100 50"><rect x="0" y="0" width="100" height="50"/></svg>
    <h1 id="heading-1">Welcome</h1>
    <button id="button-1" type="button">Go</button>
    <div id="video-1" class="video-player"><video><source src="a.webm"></video><button>Play</button></div>
  </div>
</body>
</html>
`;

describe('checkHref: a section of this page or of another', () => {
    it('reads the name after the "#"', () => {
        assert.deepEqual(L.checkHref('#prices', 'index.html'), { fragment: 'prices' });
        assert.deepEqual(L.checkHref('#über-uns', 'index.html'), { fragment: 'über-uns' });
        assert.deepEqual(L.checkHref('about.html#team', 'index.html'), { page: 'about.html', fragment: 'team' });
        assert.deepEqual(L.checkHref('../index.html#top', 'pages/a.html'), { page: 'index.html', fragment: 'top' });
    });

    it('refuses a "#" with no name, or one an address would read differently', () => {
        for (const href of ['#', '#a b', '#a"b', '#%41', '#a#b', '#a&b', '#a?b', 'about.html#a%20b', '#java\tscript']) {
            assert.ok('problem' in L.checkHref(href, 'index.html'), JSON.stringify(href));
        }
    });
});

describe('sectionName and checkSectionName: a readable name, nobody else\'s', () => {
    it('is the element\'s words, lower case, joined by "-"', () => {
        assert.equal(L.sectionName('Our Prices!', 'heading', []), 'our-prices');
        assert.equal(L.sectionName('  Café  au lait ', 'heading', []), 'cafe-au-lait');
        assert.equal(L.sectionName('Everything you ever wanted to know about our wonderful shop', 'text', []), 'everything-you-ever-wanted-to-know-about');
    });

    it('falls back to what the element is, and never starts with a digit', () => {
        assert.equal(L.sectionName('', 'picture', []), 'picture');
        assert.equal(L.sectionName('!!!', 'section', []), 'section');
        assert.equal(L.sectionName('2026 prices', 'heading', []), 'heading-2026-prices');
    });

    it('is never one the page has, in any capitals', () => {
        assert.equal(L.sectionName('Prices', 'heading', ['prices']), 'prices-2');
        assert.equal(L.sectionName('Prices', 'heading', ['Prices', 'prices-2']), 'prices-3');
    });

    it('takes a typed name that is a plain id, and says why not otherwise', () => {
        assert.equal(L.checkSectionName('our-prices', ['top']), undefined);
        assert.equal(L.checkSectionName('Team_2', []), undefined);
        for (const bad of ['', '2026', 'our prices', 'a:b', 'café', '#x', '-x']) assert.ok(L.checkSectionName(bad, []), JSON.stringify(bad));
        assert.match(L.checkSectionName('Top', ['top']), /#top already names another element/);
        assert.equal(L.checkSectionName('x'.repeat(81), []) !== undefined, true);
    });
});

describe('sectionTargets: what a link can go to', () => {
    it('offers the page\'s sections, headings and ids, in order, each found again by its path', () => {
        const targets = P.sectionTargets(IMPORTED);
        assert.deepEqual(targets.map((t) => [t.tag, t.id ?? null, t.text, t.suggested ?? null]), [
            ['header', 'top-bar', 'Shop', null],
            ['h1', null, 'Shop', 'shop'],
            ['section', null, 'Our Prices! Cheap.', 'our-prices-cheap'],
            ['h2', null, 'Our Prices!', 'our-prices'],
            ['svg', 'logo', '', null],
            ['h2', null, 'Café', 'cafe'],
        ], 'not a shape inside a drawing, a script, or an id a link cannot point at as it is');
        for (const t of targets) assert.equal(P.findByPath(IMPORTED, t.path).tagName, t.tag);
    });

    it('never suggests a name the page has', () => {
        const page = IMPORTED.replace('<p>Cheap.</p>', '<p id="our-prices">Cheap.</p>');
        assert.equal(P.sectionTargets(page).find((t) => t.text === 'Our Prices!').suggested, 'our-prices-2');
    });

    it('on a page made in Draw2Code, offers everything placed on it, but not a video player\'s parts', () => {
        assert.deepEqual(P.sectionTargets(GENERATED).map((t) => t.id), ['rect-1', 'heading-1', 'button-1', 'video-1']);
    });

    it('finds nothing on a page with no body to speak of', () => {
        assert.deepEqual(P.sectionTargets('<p>hi</p>').map((t) => t.tag), []);
    });
});

describe('nameSection and renameRules', () => {
    it('gives the element the id in place, and says which marker its rules were under', () => {
        const page = IMPORTED.replace('<h2>Café</h2>', '<h2 data-d2c="4">Café</h2>');
        const named = P.nameSection(page, { path: [2] }, 'cafe');
        assert.equal(named.html, page.replace('<h2 data-d2c="4">', '<h2 data-d2c="4" id="cafe">'));
        assert.equal(named.marker, '[data-d2c="4"]');
        assert.deepEqual(P.nameSection(named.html, { path: [2] }, 'cafe'), { html: named.html, changed: false });
    });

    it('refuses an element named already, and a name another element has', () => {
        assert.match(P.nameSection(IMPORTED, { path: [0] }, 'shop').problem, /named #top-bar already/);
        assert.match(P.nameSection(IMPORTED, { path: [2] }, 'logo').problem, /#logo already names another element/);
        assert.match(P.nameSection(IMPORTED, { path: [9] }, 'x').problem, /no longer in the page/);
    });

    it('moves the rules, their pseudo-classes and " > *" with them, in their places', () => {
        const rules = { '#a': { color: 'red' }, '[data-d2c="4"]': { color: 'blue', left: '1px' }, '[data-d2c="4"]:hover': { color: 'green' },
            '[data-d2c="40"]': { color: 'pink' }, '#cafe': { left: '2px' } };
        assert.deepEqual(Object.entries(P.renameRules(rules, '[data-d2c="4"]', '#cafe')), [
            ['#a', { color: 'red' }],
            ['#cafe', { color: 'blue', left: '2px' }],
            ['#cafe:hover', { color: 'green' }],
            ['[data-d2c="40"]', { color: 'pink' }],
        ]);
        assert.equal(P.renameRules(rules, '[data-d2c="9"]', '#x'), rules, 'nothing to move: the same object');
    });
});

describe('applyEdit: a link to a section, named in the same edit', () => {
    const makeSite = () => {
        const work = fs.mkdtempSync(path.join(os.tmpdir(), 'd2c-sections-'));
        fs.writeFileSync(path.join(work, 'index.html'), IMPORTED);
        fs.writeFileSync(path.join(work, 'about.html'), GENERATED);
        const read = (page = 'index.html') => fs.readFileSync(path.join(work, page), 'utf8');
        const rules = () => (fs.existsSync(E.overridesStore(work)) ? JSON.parse(fs.readFileSync(E.overridesStore(work), 'utf8'))['index.html'] : undefined);
        const link = (op, page = 'index.html') => E.applyEdit(work, page, { op: 'link', ...op });
        return { work, read, rules, link, done: () => fs.rmSync(work, { recursive: true, force: true }) };
    };

    it('names the section and makes the link, and one snapshot puts both back', () => {
        const { work, read, link, done } = makeSite();
        const before = E.snapshotPage(work, 'index.html');
        // The <h1> becomes a link to the "Café" heading.
        assert.equal(link({ ref: { path: [0, 0] }, href: '#cafe', anchor: { path: [2] } }).error, undefined);
        assert.match(read(), /<h2 id="cafe">Café<\/h2>/);
        assert.match(read(), /<a href="#cafe" data-d2c-was="h1">Shop<\/a>/);
        E.restorePage(work, before);
        assert.equal(read(), IMPORTED, 'the undo step holds the name and the link together');
        done();
    });

    it('moves the rules a marked section had to its new id', () => {
        const { work, read, rules, link, done } = makeSite();
        assert.equal(E.applyEdit(work, 'index.html', { op: 'style', ref: { path: [2] }, declarations: { color: 'red' } }).error, undefined);
        assert.deepEqual(rules(), { '[data-d2c="1"]': { color: 'red' } });
        assert.equal(link({ ref: { path: [0, 0] }, href: '#cafe', anchor: { path: [2] } }).error, undefined);
        assert.deepEqual(rules(), { '#cafe': { color: 'red' } });
        assert.match(fs.readFileSync(path.join(work, 'draw2code', 'index.css'), 'utf8'), /#cafe \{\n  color: red;\n\}/);
        assert.equal(E.applyEdit(work, 'index.html', { op: 'revert', ref: { id: 'cafe' } }).error, undefined);
        assert.deepEqual(rules(), {}, 'Revert element finds all of them');
        assert.match(read(), /<h2 data-d2c="1" id="cafe">/);
        done();
    });

    it('links a section that has an id as it is, and an existing link is pointed there', () => {
        const { read, link, done } = makeSite();
        assert.equal(link({ ref: { path: [2] }, href: '#top-bar' }).error, undefined);
        assert.match(read(), /<a href="#top-bar" data-d2c-was="h2">Café<\/a>/);
        assert.equal(link({ ref: { path: [2] }, href: '#logo' }).error, undefined);
        assert.match(read(), /<a href="#logo" data-d2c-was="h2">Café<\/a>/);
        done();
    });

    it('links a section of another page that is really there', () => {
        const { read, link, done } = makeSite();
        assert.equal(link({ ref: { path: [2] }, href: 'about.html#heading-1' }).error, undefined);
        assert.match(read(), /<a href="about.html#heading-1"/);
        assert.match(link({ ref: { path: [0, 0] }, href: 'about.html#nowhere' }).error, /there is no #nowhere on about.html/);
        done();
    });

    it('refuses a section that is not there, a bad name, a name taken, and naming on another page', () => {
        const { read, link, done } = makeSite();
        assert.match(link({ ref: { path: [0, 0] }, href: '#nowhere' }).error, /there is no #nowhere on this page/);
        assert.match(link({ ref: { path: [0, 0] }, href: '#2026', anchor: { path: [2] } }).error, /starts with a letter/);
        assert.match(link({ ref: { path: [0, 0] }, href: '#Logo', anchor: { path: [2] } }).error, /#logo already names another element/);
        assert.match(link({ ref: { path: [0, 0] }, href: '#logo', anchor: { path: [2] } }).error, /#logo already names another element/);
        assert.match(link({ ref: { path: [0, 0] }, href: 'about.html#x', anchor: { path: [2] } }).error, /only a link to a section of this page can name one/);
        assert.match(link({ ref: { path: [0, 0] }, href: '#shop', anchor: { path: [0] } }).error, /named #top-bar already/);
        assert.equal(read(), IMPORTED, 'nothing written');
        done();
    });
});

describe('a section link in the editor and in the published site', () => {
    const run = (html) => S.rewriteUrls(html, '/site', '/site', (p) => `vscode-resource:${p}`);

    it('the editor keeps a section of this page as it is, and a section of another page with its page', () => {
        assert.equal(run('<a href="#cafe">Café</a>'), '<a href="#cafe">Café</a>');
        assert.equal(run('<a href="about.html#team">Team</a>'), `<a href="${S.PAGE_LINK_PREFIX}about.html#team">Team</a>`);
    });

    it('Publish keeps the href and the id it goes to', () => {
        const page = IMPORTED.replace('<h2>Café</h2>', '<h2 data-d2c="4" id="cafe">Café</h2>').replace('<h1>Shop</h1>', '<a href="#cafe" data-d2c-was="h1">Shop</a>');
        const out = P.stripDraw2Code(page, 'page-index').html;
        assert.match(out, /<a href="#cafe">Shop<\/a>/);
        assert.match(out, /<h2 id="cafe">Café<\/h2>/);
    });
});

describe('following a section link in the editor (copied into the overlay)', () => {
    const PREFIX = '#draw2code-page:';

    it('reads where a link goes', () => {
        assert.deepEqual(L.sectionLink('#cafe', PREFIX), { page: '', id: 'cafe' });
        assert.deepEqual(L.sectionLink('#', PREFIX), { page: '', id: '' });
        assert.deepEqual(L.sectionLink(`${PREFIX}about.html#team`, PREFIX), { page: 'about.html', id: 'team' });
        assert.deepEqual(L.sectionLink(`${PREFIX}pages/a.html`, PREFIX), { page: 'pages/a.html', id: '' });
        assert.equal(L.sectionLink('https://example.com/#x', PREFIX), null);
    });

    it('scrolls the section to just under the bar, and no further than the page goes', () => {
        const view = { width: 800, height: 600 };
        const BAR = 112;
        // A section 900px down a page 3000px tall, the view at the top.
        assert.deepEqual(L.sectionScroll({ top: 900 + BAR, left: 10, right: 300 }, { x: 0, y: 0 }, view, BAR, 3000 + BAR), { left: 0, top: 900 });
        // Scrolled 500px already: the same place.
        assert.deepEqual(L.sectionScroll({ top: 400 + BAR, left: 10, right: 300 }, { x: 0, y: 500 }, view, BAR, 3000 + BAR), { left: 0, top: 900 });
        // Near the end: only as far as a browser would go.
        assert.deepEqual(L.sectionScroll({ top: 2900 + BAR, left: 10, right: 300 }, { x: 0, y: 0 }, view, BAR, 3000 + BAR), { left: 0, top: 3000 + BAR - 600 });
        // Off to the right of a narrow view: sideways just enough to show it.
        assert.deepEqual(L.sectionScroll({ top: BAR, left: 900, right: 1000 }, { x: 0, y: 0 }, view, BAR, 3000), { left: 200, top: 0 });
        assert.deepEqual(L.sectionScroll({ top: BAR, left: -50, right: 100 }, { x: 300, y: 0 }, view, BAR, 3000), { left: 250, top: 0 });
        // "#" alone: the top of the page.
        assert.deepEqual(L.sectionScroll(null, { x: 40, y: 700 }, view, BAR, 3000), { left: 40, top: 0 });
    });

    it('both run on their own, as they are copied into the overlay', () => {
        const link = new Function(`return (${L.sectionLink.toString()});`)();
        const scroll = new Function(`return (${L.sectionScroll.toString()});`)();
        assert.deepEqual(link(`${PREFIX}about.html#team`, PREFIX), { page: 'about.html', id: 'team' });
        assert.deepEqual(scroll({ top: 300, left: 0, right: 10 }, { x: 0, y: 0 }, { width: 800, height: 600 }, 100, 2000), { left: 0, top: 200 });
    });
});
