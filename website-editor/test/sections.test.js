// the checks and names in src/links.ts, the sections offered and named in
// src/pageEdit.ts, the link op that names one in src/pageEditor.ts, and the
// hrefs kept by the editor's view (src/siteFiles.ts) and by Publish
// (compiled to out/ by npm test's pretest).
//
