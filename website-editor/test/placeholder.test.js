// Unit tests for an input's placeholder in the page editor: setPlaceholder
// in src/pageEdit.ts and the placeholder op in src/pageEditor.ts (compiled
// to out/ by npm test's pretest).
//
// CS50 citation: I did not write these tests. I had an AI coding agent read
// my code and write tests for it, to save time, and it put this file in
// website-editor/test/. The code it tests is mine; the tests are the agent's.
// I run them with npm test.

const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const P = require('../../out/website-editor/src/pageEdit.js');
const E = require('../../out/website-editor/src/pageEditor.js');

const PAGE = `<!DOCTYPE html>
<html>
<head>
  <title>Form</title>
  <!-- Generated by Draw2Code Web Editor -->
</head>
<body>
  <div class="page">
    <input id="input-1" type="text" placeholder="Your name">
    <input id="input-2" type="email"/>
    <textarea id="notes" placeholder="Notes"></textarea>
    <p id="text-1">Hello</p>
  </div>
</body>
</html>
`;

describe('setPlaceholder: the words an empty field shows', () => {
    it('changes the attribute in place, and nothing else', () => {
        const out = P.setPlaceholder(PAGE, { id: 'input-1' }, 'Full name & "nickname"');
        assert.equal(out.html, PAGE.replace('placeholder="Your name"', 'placeholder="Full name &amp; &quot;nickname&quot;"'));
    });

    it('adds one to a field without, also a self-closed one', () => {
        assert.match(P.setPlaceholder(PAGE, { id: 'input-2' }, 'you@example.com').html, /<input id="input-2" type="email" placeholder="you@example.com"\/>/);
        assert.match(P.setPlaceholder(PAGE, { id: 'notes' }, 'More').html, /<textarea id="notes" placeholder="More">/);
    });

    it('takes the attribute away when emptied, and a line break becomes a space', () => {
        assert.match(P.setPlaceholder(PAGE, { id: 'input-1' }, '').html, /<input id="input-1" type="text">/);
        assert.match(P.setPlaceholder(PAGE, { id: 'input-1' }, 'a\nb').html, /placeholder="a b"/);
    });

    it('changes nothing when it is already so', () => {
        assert.deepEqual(P.setPlaceholder(PAGE, { id: 'input-1' }, 'Your name'), { html: PAGE, changed: false });
        assert.deepEqual(P.setPlaceholder(PAGE, { id: 'input-2' }, ''), { html: PAGE, changed: false });
    });

    it('is only for fields', () => {
        assert.match(P.setPlaceholder(PAGE, { id: 'text-1' }, 'x').problem, /<p> has no placeholder/);
        assert.match(P.setPlaceholder(PAGE, { id: 'gone' }, 'x').problem, /no longer in the page/);
    });
});

describe('applyEdit: the placeholder op', () => {
    it('writes the page only, as one step to undo', () => {
        const work = fs.mkdtempSync(path.join(os.tmpdir(), 'd2c-placeholder-'));
        fs.writeFileSync(path.join(work, 'index.html'), PAGE);
        const before = E.snapshotPage(work, 'index.html');
        const result = E.applyEdit(work, 'index.html', { op: 'placeholder', ref: { path: [0, 0] }, text: 'Your full name' });
        assert.deepEqual(result, { changed: [path.join(work, 'index.html')] });
        assert.match(fs.readFileSync(path.join(work, 'index.html'), 'utf8'), /<input id="input-1" type="text" placeholder="Your full name">/);
        assert.equal(fs.existsSync(E.overridesStore(work)), false, 'no rule, no marker');
        assert.deepEqual(E.applyEdit(work, 'index.html', { op: 'placeholder', ref: { path: [0, 0] }, text: 'Your full name' }), { changed: [] });
        assert.match(E.applyEdit(work, 'index.html', { op: 'placeholder', ref: { id: 'text-1' }, text: 'x' }).error, /has no placeholder/);
        E.restorePage(work, before);
        assert.equal(fs.readFileSync(path.join(work, 'index.html'), 'utf8'), PAGE);
        fs.rmSync(work, { recursive: true, force: true });
    });
});
